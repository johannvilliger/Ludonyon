// Répartit un total entier sur n objets, chacun à base ou base+1 francs, de
// sorte que la somme retombe exactement sur le total (méthode des plus
// grands restes) — jamais d'arrondi qui ferait dévier le total du vendeur.
export function repartirValeur(total: number, n: number): number[] {
  if (n === 0) return [];
  const base = Math.floor(total / n);
  const reste = total - base * n;
  return Array.from({ length: n }, (_, i) => base + (i < reste ? 1 : 0));
}
